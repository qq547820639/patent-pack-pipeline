def title_generic_only(value):
    """R15 第二支：名称删尽 TITLE_GENERIC_WORDS 与填充字后是否一个实义字符都不剩。"""
    residue = value
    for word in TITLE_GENERIC_WORDS:
        residue = residue.replace(word, '')
    return not TITLE_FILLER.sub('', residue)


