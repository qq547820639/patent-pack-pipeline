class Finding:
    __slots__ = ('rule', 'path', 'line', 'msg', 'quote')

    def __init__(self, rule, path, line, msg, quote=''):
        self.rule, self.path, self.line, self.msg, self.quote = rule, path, line, msg, quote

    def __str__(self):
        loc = f'{self.path}:{self.line}' if self.line else self.path
        q = f' -> {self.quote}' if self.quote else ''
        return f'  FAIL {self.rule} {loc}: {self.msg}{q}'


def section_body(lines, head_re):
    """返回 (起始行号 1-based, 该节正文行列表)；找不到返回 (None, [])。

    第 46 轮起**按层级断尾**：从命中的标题级数往下走，止于下一个级数不高于它的标题。
    从前它止于任何 `^#{1,3}` 标题，于是「## 说明书摘要」底下只要出现一个 `### 技术效果`
    子标题，窗口就在子标题**之前**截断——"块里有没有标题"这件事根本读不到，
    而读不到与没有在同一份报告里完全同形（R17 就是被这一条挡住的，见 R17 那一格）。
    命中的那一行若不是 markdown 标题（`head_re` 允许裸文本时），退回旧断法：
    没有级数可比，就按"下个标题即断"处理，不猜。"""
    for i, ln in enumerate(lines):
        if head_re.match(ln.strip()):
            hm = HEAD_LEVEL.match(ln)
            if hm is None:
                body = []
                for j in range(i + 1, len(lines)):
                    if NEXT_SECTION.match(lines[j]):
                        break
                    body.append(lines[j])
                return i + 1, body
            level = len(hm.group(1))
            body = []
            for j in range(i + 1, len(lines)):
                nj = HEAD_LEVEL.match(lines[j])
                if nj and len(nj.group(1)) <= level:
                    break
                body.append(lines[j])
            return i + 1, body
    return None, []


def doc_region(lines, head_re):
    """层级区域：从 head_re 命中的标题起，到下一个**级数不高于它**的标题止。
    section_body 在任何下个标题就断——说明书那一份里五节全是 ### 小节，
    用它会把区域截在「### 技术领域」，四条禁令等于没判。找不到返回 (None, [])。"""
    for i, ln in enumerate(lines):
        if head_re.match(ln.strip()):
            level = len(ln) - len(ln.lstrip('#'))
            body = []
            for j in range(i + 1, len(lines)):
                mj = re.match(r'^(#{1,6})\s', lines[j])
                if mj and len(mj.group(1)) <= level:
                    break
                body.append(lines[j])
            return i + 1, body
    return None, []


def _head_split(line):
    """标题行 → (级数, 归一后的节名)；非标题行返回 (0, '')。
    认法与 `rebuild_package.head_names` 同一条：剥井号、剥尾部括注、剥编号前缀后**全等**才认，
    正文里提到这几个词不算一个节（docx 通道由 docx_text 按 w:pStyle 还原成同样的 # 行）。"""
    m = _HD.match(line.strip())
    if not m:
        return 0, ''
    t = _HD_PAREN.sub('', m.group(2)).strip()
    return len(m.group(1)), _HD_NUM.sub('', t).strip()


def spec_doc_blocks(lines):
    """说明书区域 = 「说明书」标题那一块 ∪ 细则第二十条一款那五节各自的标题块（多块并集）。

    与 doc_region 的区别就是本轮修的那个假阴性：区域**不锚标题层级**，改锚法条自己列举的节名——
    生产模板把 说明书摘要／权利要求书／说明书／技术领域／背景技术／发明内容／附图说明／
    具体实施方式／图中标记说明 **全部写成 `##`**，于是"止于下一个 ≤2 级标题"的划法在真包上
    只剩 `## 说明书` 底下那一行占位，R11 与 R10 说明书面基本不开火。
    任一层级都认（`## 具体实施方式` 与 `### 具体实施方式` 同等入域），同名出现多处时全部并入
    （生产包里 `## 附图说明` 真有两处：一处模板占位、一处 rebuild 追加的真内容）。
    每块止于下一个级数不高于它的标题、或 SPEC_REGION_STOP 里那些节名（权利要求书那一类）。

    返回 [(该块标题行的 1-based 行号, 该块正文行列表), ...]，按文件顺序、互相不重叠：
    嵌套在「说明书」块里的那些小节会被并成一段，所以同一行只会被报一次。调用方仍按
    `dstart + 1 + off` 打位点，**每条 Finding 的行号由它自己所在那一块算出**——
    多块并集下拿一个全局原点必然漂（本仓"绝对坐标常驻档"那条教训）。
    一块都没有 ⇒ 返回 []：调用方按"不适用"处理，不出提示行，也不折成合规。"""
    spans = []
    for i, ln in enumerate(lines):
        raw = ln.strip()
        # 级数按井号数现取（与 doc_region 同一口径，`##说明书` 这种无空格写法也照认），
        # 节名只取规范标题行（"# 后接空白"）的归一形式——正文里出现"技术领域"四个字不算一个节。
        level = len(raw) - len(raw.lstrip('#')) if raw.startswith('#') else 0
        if not level:
            continue
        title = _head_split(raw)[1]
        if not (SPEC_DOC_HEAD.match(raw) or title == '说明书' or title in SPEC_SECTIONS):
            continue
        j = i + 1
        while j < len(lines):
            jlevel, jtitle = _head_split(lines[j])
            if jlevel and (jlevel <= level or jtitle in SPEC_REGION_STOP):
                break
            j += 1
        spans.append((i, j - 1))
    covered = [False] * len(lines)
    for a, b in spans:
        for k in range(a + 1, b + 1):
            covered[k] = True
    blocks, k = [], 0
    while k < len(lines):
        if not covered[k]:
            k += 1
            continue
        e = k
        while e + 1 < len(lines) and covered[e + 1]:
            e += 1
        # k 是"块内第一行正文"的 0-based 下标，也就是它上面那行标题的 1-based 行号：
        # dstart + 1 + off 因此仍指向那一行自己的真行号（off 从块首正文起算）。
        blocks.append((k, lines[k:e + 1]))
        k = e + 1
    return blocks


def check_text(path, text, allowed_pub_nos=None, brand_terms=None, marks=None, docx_graphs=None):
    """对单份文书文本跑全部判据，返回 (findings, notes)。notes 为不计入违规的说明行。

    docx_graphs：R14 的 zip 级图形部件普查读数（见 `docx_graph_census`）。CLI 侧由 main() 传；
    没传而对一个 .docx 路径跑判据时，本函数自己补算一次——拿"没普查"当"没有图形部件"就是
    这条判据要避开的那个假绿（md 通道 census 恒 0，不涉及这一格）。"""
    findings, notes = [], []
    lines = text.splitlines()

    for i, raw in enumerate(lines, 1):
        for w in BANNED_ALWAYS:
            if w in raw:
                findings.append(Finding('R1 绝对化措辞', path, i, f'禁用词「{w}」', raw.strip()[:60]))
        if '首次' in raw and FIRST_TIME_CTX.search(raw):
            findings.append(Finding('R1 绝对化措辞', path, i, '「首次」用于新颖性声明', raw.strip()[:60]))

        for m in PLACEHOLDER_TOKEN.finditer(raw):
            token = m.group(0)
            if not PLACEHOLDER_KIND.match(token):
                findings.append(Finding(
                    'R2b 占位符格式', path, i,
                    '方括号占位须以「待」开头或用【占位】，否则不是本仓库规定的占位式样', token))
            elif token.startswith(CONFIRM3_PREFIX) and not CONFIRM3_SHAPE.match(token):
                findings.append(Finding(
                    'R2c 三字段占位', path, i,
                    '【待设计方确认：…】须为 对象｜阻塞项｜关闭判据 三字段', token))
        if BARE_TODO.search(raw):
            findings.append(Finding('R2a 占位符格式', path, i,
                                    '裸 TODO/FIXME/XXX 字样（TBD/TBC 属 §1 允许的状态标注，不判）',
                                    raw.strip()[:60]))

    cstart, cbody = section_body(lines, CLAIMS_HEAD)
    if cstart is not None:
        for off, ln in enumerate(cbody):
            m = CLAIM_ANNOTATION.search(ln)
            if m:
                findings.append(Finding('R3 权文内占位注释', path, cstart + 1 + off,
                                        '占位说明应移至说明书', m.group(0)))

    astart, abody = section_body(lines, ABSTRACT_HEAD)
    if astart is not None:
        n = len(re.sub(r'\s', '', ''.join(abody)))
        if n > ABSTRACT_LIMIT:
            findings.append(Finding('R4 摘要字数', path, astart,
                                    f'摘要含标点 {n} 字 > {ABSTRACT_LIMIT}'))

    # R10：两节各判各的，法源写在消息里——同一张词表打在摘要上引 26 条、打在简要说明上引 31 条，
    # 报成同一句话的话，读者就分不出这条红是哪一件文书欠的（判据消息要带本档专属成因词）。
    # 交底书的「摘要建议稿」与申请文件的「说明书摘要」共用 ABSTRACT_HEAD：前者就是后者的前身，
    # 在提交前拦比交出去再补正便宜。
    for head, ref in R10_SCOPE:
        hstart, hbody = section_body(lines, head)
        if hstart is None:
            continue
        for off, ln in enumerate(hbody):
            for w in COMMERCIAL:
                if w in ln:
                    findings.append(Finding('R10 摘要/简要说明宣传用语', path,
                                            hstart + 1 + off,
                                            f'商业性宣传用语「{w}」——{ref}', ln.strip()[:60]))

    # R11＋R10 的说明书面＋R14：三条判据**共用同一个区域**（`spec_doc_blocks`，多块并集、逐块原点
    # dstart + 1 + off）。细则第二十条三款"……并不得使用'如权利要求……所述的……'
    # 一类的引用语，也不得使用商业性宣传用语"；《专利审查指南》（2023）第一部分第一章 §4.2
    # 那句「说明书文字部分可以有化学式、数学式或者表格，但不得有插图。」管的也是**同一份说明书**，
    # 所以 R14 另划一套区域只会跟这套在第 40 轮修过的划法分叉（区域内每一行三个问题一起问）。
    # 词表复用 R10 的 COMMERCIAL（一张词表三张面，不抄第二份）；引用语是独立正则；
    # 图片形状复用 SPEC_IMAGE（与权要那一族的 Q7 同一个对象）。
    # 一块都没有 ⇒ 三条都不适用（不出提示行），与 R10 两节的口径一致；也不许因为区域变了就把
    # "看不见"折成"合规"或新添一条"未判"噪声（R14 的未判只由下面那格 census 出，且只在 docx 通道）。
    # 位点 dstart + 1 + off 由**当前这一块**给出。
    spec_blocks = spec_doc_blocks(lines)
    r14_hits = 0
    for dstart, dbody in spec_blocks:
        for off, ln in enumerate(dbody):
            m = CLAIMS_QUOTE_REF.search(ln)
            if m:
                findings.append(Finding('R11 说明书引用语', path, dstart + 1 + off,
                                        f'说明书里用"{m.group(0)}"指回权利要求'
                                        '——细则第二十条三款：不得使用该类引用语', ln.strip()[:60]))
            for w in COMMERCIAL:
                if w in ln:
                    findings.append(Finding('R10 说明书宣传用语', path, dstart + 1 + off,
                                            f'商业性宣传用语「{w}」——细则第二十条三款：'
                                            '说明书里不得使用商业性宣传用语', ln.strip()[:60]))
            im = SPEC_IMAGE.search(ln)
            if im:
                r14_hits += 1
                findings.append(Finding('R14 说明书文字部分有插图', path, dstart + 1 + off,
                                        '说明书文字部分不得有插图——《专利审查指南》（2023）'
                                        '第一部分第一章 §4.2「说明书文字部分可以有化学式、数学式'
                                        '或者表格，但不得有插图」（PDF p25／印刷页 1-9）；'
                                        '化学式／数学式／表格三种豁免形态在文本面上不是图片形状，'
                                        '本条是结构上碰不到它们，不是显式排掉',
                                        ln.strip()[:60]))

    # R14 的三态第三支：docx 的**盲区**不折成合规。
    # docx_text 只把**段落**里含 drawing/object/pict 的折成一行 `![](docx-embedded-object)`，
    # 表格格子里嵌的图（表格分支按格取文）与页眉页脚里的图（只读 word/document.xml）它读不到
    # ⇒ 文本面零命中不等于这份 Word 件没有插图。zip 级 census>0 而文本面 0 命中 ⇒ 出一条未判 note；
    # census==0 ⇒ 已判零违规（不出行）；md 通道 census 恒 0（图片形状就在文本面上，没有盲区）。
    # 退码语义不动：未判与合规都是 0，只有真违规是 1（见 main 的 `1 if total else 0`）。
    if spec_blocks and r14_hits == 0:
        if docx_graphs is None:
            # CLI 侧由 main() 与 read_text 同一个 try 里算好传进来（读不动 ⇒ rc=2）；
            # 直接调 check_text 的路径没传就在当场补算一次，不拿"没普查"当"普查过且为零"。
            docx_graphs = docx_graph_census(path)
        if docx_graphs:
            notes.append('R14 未判（docx 有图形部件但文本面看不见：表格格／页眉那一类）')


    # R12／R13：同一张「标记｜名称」对照表，三面三种写法（第四面是 check_claims 的 Q5）：
    #   摘要——标记应当加括号（指南第二部分第二章 §2.4，PDF p159／印刷页 2-23 逐字）；
    #   具体实施方式——标记紧跟技术名称、**不加**括号（同部分 §2.2.6，PDF p156／2-20 逐字）。
    # 号集只认表里登记的「名称↔号」对，表外的自由数字（"拉脱力 90N""2020 年"）一律不当标记——
    # 与 Q5 同一条防线，否则这两把尺子只会造假红。包内没有那张表 ⇒ 两条未判（不折成合规）；
    # 区域不在本份文书 ⇒ 该条不适用，不出提示行（与 R11 同口径）。
    # R17 摘要文字部分不得使用标题——《专利审查指南》（2023）第一部分第一章 §4.5.1，
    # 本机留底 txt:856-857（`<<<PAGE 27>>>` 在 txt:844、页眉两行 txt:845-846 抄引文要跳过，
    # 印刷页 1-11），逐字：「摘要文字部分不得使用标题，文字部分（包括标点符号）
    # 不得超过 300 个字。」这一支只报**第一个**块内标题：一条红足够指出该改的地方，
    # 而多报几条会让"一份摘要里有三个小标题"这种形状的计数变成噪音。
    r17_start, r17_body = section_body(lines, ABSTRACT_HEAD)
    if r17_start is None:
        notes.append('未找到摘要节，R17 未判、R18 未判（不折成合规）')
    else:
        for off, ln in enumerate(r17_body):
            if HEAD_LEVEL.match(ln):
                findings.append(Finding(
                    'R17 摘要文字部分有标题', path, r17_start + 1 + off,
                    '摘要块内出现标题行「' + ln.strip()[:40] + '」——§4.5.1 逐字：'
                    '摘要文字部分不得使用标题（摘要是写明名称、技术领域、要解决的技术问题、'
                    '技术方案要点与主要用途的连续正文，小标题不属于它）'))
                break
        # R18 摘要文字部分应当写明发明的名称——§4.5.1 逐字（txt:851-854）：
        # 「摘要文字部分应当写明发明的名称和所属的技术领域……未写明发明名称或者
        # 不能反映技术方案要点的，应当通知申请人补正」。
        # 只有"名称"这一件判得动：它是可比对的字符串（源＝同包交底书那一行字段，与 R16 同一个取法）。
        # 「所属技术领域／技术问题／要点／用途」是内容判断，做不成判据——本仓不拿关键词匹配冒充判定，
        # 那三条按裁决收口（第 47 轮，原 #29③）：出现可比对的载体才重开，例如摘要里另立"技术领域"字段行。
        filled = [k for k, x in enumerate(r17_body) if x.strip()]
        if not filled:
            notes.append('摘要块是空的，R18 未判（空块不折成"没写名称"的违规）')
        else:
            r18_names = case_titles(path)
            if r18_names is None:
                notes.append('同包 01_交底书 里读不到发明名称字段，R18 未判')
            else:
                flat = re.sub(r'\s', '', ''.join(r17_body))
                if not any(nm in flat for nm in r18_names):
                    findings.append(Finding(
                        'R18 摘要未写明发明名称', path, r17_start + 1 + filled[0],
                        '摘要块正文里找不到本案发明名称（' + '／'.join(r18_names[:3]) + '）——'
                        '§4.5.1 逐字：摘要文字部分应当写明发明的名称……'
                        '未写明发明名称或者不能反映技术方案要点的，应当通知申请人补正'))

    r13_start, r13_body = section_body(lines, ABSTRACT_HEAD)
    r12_start, r12_body = doc_region(lines, SPEC_IMPL_HEAD)
    if not marks:
        if r13_start is not None or r12_start is not None:
            notes.append('文里有摘要／具体实施方式区域，但包内没有「标记｜名称」对照表 '
                         '→ R12/R13 未判（看不见不等于合规）')
    else:
        for nm, num in sorted(marks.items()):
            bare = re.compile(re.escape(nm) + r'\s*' + re.escape(num) + r'(?![0-9])')
            pbr = re.compile(re.escape(nm) + r'\s*[（(]\s*' + re.escape(num) + r'\s*[）)]')
            if r13_start is not None:
                for off, ln in enumerate(r13_body):
                    m = bare.search(ln)
                    if m:
                        findings.append(Finding(
                            'R13 摘要标记未加括号', path, r13_start + 1 + off,
                            f'摘要里「{m.group(0).strip()}」的标记 {num} 没放进括号'
                            '——指南 §2.4：摘要文字部分出现的附图标记应当加括号',
                            ln.strip()[:60]))
            if r12_start is not None:
                for off, ln in enumerate(r12_body):
                    m = pbr.search(ln)
                    if m:
                        findings.append(Finding(
                            'R12 具体实施方式标记加括号', path, r12_start + 1 + off,
                            f'具体实施方式里「{m.group(0).strip()}」给标记 {num} 加了括号'
                            '——指南 §2.2.6：应放在相应技术名称后面、不加括号'
                            '（不加括号是这一面的要求，与权利要求书的 Q5 相反）',
                            ln.strip()[:60]))

    if allowed_pub_nos is not None:
        start, body = section_body(lines, BACKGROUND_HEAD)
        if start is None:
            notes.append('背景技术节未找到，未核公开号归属')
        else:
            seen, missing = set(), []
            for off, ln in enumerate(body):
                for m in PUB_NO.finditer(ln):
                    no = re.sub(r'\s', '', m.group(0)).upper()
                    seen.add(no)
                    if no not in allowed_pub_nos:
                        missing.append((off + start + 1, no))
            for ln_no, no in missing:
                findings.append(Finding('R5 公开号越界', path, ln_no,
                                        '该公开号不在检索报告已核验清单内'))
            notes.append(f'背景技术公开号 {len(seen)} 个已核，越界 {len(missing)} 个')
    else:
        nums = set(re.sub(r'\s', '', x).upper() for x in PUB_NO.findall(text))
        if nums:
            notes.append(f'文书含 {len(nums)} 个公开号，未给 --search-report，R5 未核（不折算合规也不折算违规）')
    # R6 商标/型号禁令（铁律 4）：须由调用方给出本案的型号/商标清单，
    # 不自动猜——IP67、M5、45#钢 这类标准/规格写法会被模式匹配误伤
# （语料就在常驻用例里：tests/test_scripts.py 的 "紧固件按 M5 螺纹、防护等级 IP67、材料 45#钢" 那一档）。
    for term in (brand_terms or []):
        if not term:
            continue
        pat = re.compile(re.escape(term), re.I)
        for i, raw in enumerate(lines, 1):
            if pat.search(raw):
                findings.append(Finding('R6 商标型号', path, i,
                                        f'出现本案型号/商标「{term}」，应改通用名', raw.strip()[:60]))
    if brand_terms is None:
        pub = set(re.sub(r'\s', '', x).upper() for x in PUB_NO.findall(text))
        cand = [t for t in re.findall(r'\b[A-Za-z]{2,}[-_ ]?\d{2,}\b', text)
                if t.upper() not in pub]
        notes.append(f'未给 --brand-terms，R6 未核'
                     + (f'（另有 {len(set(cand))} 处型号形态待人工判）' if cand else ''))

    # R7 发明名称字数：法条给的是两根轴，不是一根。25 是"一般不得超过"（软，本仓模板 §0 同口径），
    # 60 才是"不得超过"（硬）。只有一根轴时把 26 字判红＝把指南明写允许的情形退回修订。
    # 字段判**每一处**出现，不是只判第一处（第 44 轮改：从前这里 `break` 在第一行，
    # 于是"第一行合规、第二行藏一个违规名"从两把尺子里一起消失——一行的空隙不该是免检通道）。
    title_seen = False
    # R19 的权威源整份文书只取一次（case_titles 要走同包目录，逐处重取是白活）：
    # None＝还没取，()＝取了但读不到，非空 tuple＝取到了。
    r19_names = None
    r19_unjudged = False
    for i, raw in enumerate(lines, 1):
        m = TITLE_FIELD.match(raw)
        if m:
            title_seen = True
            val = m.group(1)
            n = len(re.sub(r'\s', '', val))
            if n > TITLE_HARD_MAX:
                findings.append(Finding('R7 发明名称字数', path, i,
                                        f'发明名称 {n} 字 > {TITLE_HARD_MAX}'
                                        '（《专利审查指南》2023 第一部分第一章 §4.1.1'
                                        '「……必要时可不受此限，但也不得超过 60 个字」——60 是硬上限）'))
            elif n > TITLE_SOFT_MAX:
                notes.append(f'发明名称 {n} 字 > 本仓模板 §0 的 {TITLE_SOFT_MAX} 字口径，但不判红：'
                             '《专利审查指南》2023 第一部分第一章 §4.1.1 明写'
                             '「发明名称一般不得超过 25 个字，必要时可不受此限，但也不得超过 60 个字」'
                             f'——"一般""必要时可不受此限"使 {TITLE_SOFT_MAX} 只是软上限，'
                             f'只有 {TITLE_HARD_MAX} 是硬上限（超上限才判红）；'
                             '本仓模板 §0 仍按 ≤25 要求，那是自家比法条更严的口径，不折算成违规')
            # R15 同一段落另两句禁令，读的是同一个字段，所以挂在同一个循环里（一次匹配两处判）。
            mv = TITLE_VAGUE.search(val)
            if mv:
                findings.append(Finding('R15 发明名称含糊词', path, i,
                                        f'发明名称含含糊词「{mv.group(0)}」——《专利审查指南》2023'
                                        ' 第一部分第一章 §4.1.1 逐字：也不得含有含糊的词语，'
                                        '例如“及其他”“及其类似物”等'))
            if title_generic_only(val):
                findings.append(Finding('R15 发明名称纯笼统词', path, i,
                                        f'发明名称「{val}」删尽 §4.1.1 点名的笼统词'
                                        f'（{"、".join(TITLE_GENERIC_WORDS)}）与填充字后一个实义字符都不剩——'
                                        '逐字：也不得仅使用笼统的词语，致使未给出任何发明信息'))
            # R19 同包内每一处「发明名称：」字段都得是同一个值。
            # 法源两层，各引各的：《专利法实施细则》第二十条一款首句（行政法规库合并全文，
            # 「……说明书应当写明发明或者实用新型的名称，该名称应当与请求书中的名称一致」）
            # ＋《专利审查指南》第一部分第一章 §4.1.1 首句（本机留底 txt:619＝PDF p20／印刷页 1-4，
            # 「请求书中的发明名称和说明书中的发明名称应当一致」）。
            # 权威源与 R16／R18 同一个 hub（同包 01_交底书 那一行字段）：交底书自己永远静默
            # （它的值本就在集合里），开火的只会是改了值的那份副本——正是抄进请求书时最容易发生的事。
            if r19_names is None:
                r19_names = case_titles(path)
            flat_val = re.sub(r'\s', '', val)
            if not r19_names:
                r19_unjudged = True
            elif flat_val not in r19_names:
                findings.append(Finding(
                    'R19 发明名称与本案不一致', path, i,
                    f'这一处发明名称是「{val}」，同包 01_交底书 写的是'
                    f'「{r19_names[0]}」——细则第二十条一款首句＋指南 §4.1.1 首句'
                    '都要求请求书／说明书里的名称与权威那一份一致（副本漂移就是从这里进交付物的）'))
    if not title_seen:
        notes.append('未找到「发明名称：」字段，R7 未核、R15 未核')
    if r19_unjudged:
        notes.append('同包 01_交底书 里读不到「发明名称：」字段，R19 未判（既不折成合规，也不折成违规）')

    # R20 发明人那一行。§4.1.2 那句里有两条禁令，只有"不得填单位或者集体，以及人工智能名称"
    # 拿得到逐字样本（课题组／人工智能）；"不得使用笔名或者其他非正式的姓名"没有样本可枚举，
    # 判它就是拿一把自造词表去猜哪串字算笔名——那条不做，理由写在上面的常量旁注里。
    # **每处都判**：发明人可以有多位、一行一个，第二处不许成为免检通道（R15 同一条纪律）。
    r20_placeholder = False
    for i, raw in enumerate(lines, 1):
        m2 = INVENTOR_FIELD.match(raw)
        if not m2:
            continue
        val2 = m2.group(1)
        if PLACEHOLDER_TOKEN.search(val2):
            r20_placeholder = True
            continue
        hit = next((t for t in INVENTOR_BANNED if t in val2), None)
        if hit:
            findings.append(Finding(
                'R20 发明人不是个人姓名', path, i,
                f'发明人「{val2}」带着指南 §4.1.2 逐字点名的「{hit}」——那句是'
                '"发明人应当是个人，请求书中不得填写单位或者集体，以及人工智能名称，'
                '例如不得写成“××课题组”或者“人工智能××”等"，发明人要用本人真实姓名'
                '（申请人是单位本来合法：同一个词写在申请人行不触发本条）'))
    if r20_placeholder:
        notes.append('发明人那一行还是占位（骨架期无人填），R20 未判（不折成合规）')

    # R21 地址那一行：同一个形状（字段行 + 法条逐字样本），判点从"是不是个人"换成"有没有号码"。
    r21_placeholder = False
    for i, raw in enumerate(lines, 1):
        m3 = ADDRESS_FIELD.match(raw)
        if not m3:
            continue
        val3 = m3.group(1)
        if PLACEHOLDER_TOKEN.search(val3):
            r21_placeholder = True
            continue
        if ADDRESS_UNIT in val3 and not ADDRESS_DIGIT.search(val3):
            findings.append(Finding(
                'R21 地址被单位名称代替', path, i,
                f'地址「{val3}」带着单位名称「{ADDRESS_UNIT}」却一个数字都没有（街道门牌号码／邮编／'
                '电话一个都不在）——§4.1.7 逐字：地址中可以包含单位名称，但单位名称不得代替地址，'
                '例如不得仅填写××省××大学；本国地址那三种并列写法都以「街道门牌号码」收尾'))
    if r21_placeholder:
        notes.append('地址那一行还是占位（骨架期无人填），R21 未判（不折成合规）')

    # R22／R23 两个人数上限：字段行一行一人，数行数就够了，不必从自由文本里猜名字。
    lim_findings, lim_notes = field_line_limits(path, lines)
    findings += lim_findings
    notes += lim_notes

    # R16 说明书第一页第一行（§4.2 那两句禁令，txt:763-767＝PDF p24／印刷页 1-8）。
    # 判的是**第一条有内容的行**：md 文件开头那个空行是排版壳，不是"第一行没写东西"。
    # 同句里"左右居中"与"发明名称与说明书正文之间应当空一行"不判——都是排版属性，
    # 文本通道读不到居中，Word 通道里"空一行"表现为空段落而 docx_text 不吐空段落，
    # 拿它们判红等于把判据的缺席写成文档的违规（这一面写在下面的"未核"话术里，不藏）。
    if spec_doc_scope(path):
        first = next(((i, ln) for i, ln in enumerate(lines, 1) if ln.strip()), None)
        if first:
            fno, fraw = first
            if SPEC_HEAD_PREFIX.match(fraw):
                findings.append(Finding(
                    'R16 说明书首行冠了字样', path, fno,
                    '说明书第一行以「发明名称：／名称：」起头——《专利审查指南》2023 第一部分'
                    '第一章 §4.2 逐字：发明名称前面不得冠以"发明名称"或者"名称"等字样'))
            else:
                names = case_titles(path)
                body = re.sub(r'\s', '', MD_HEAD_SHELL.sub('', fraw))
                if names is None:
                    notes.append('同包 01_交底书 里读不到「发明名称：」字段，R16 首行同一性未判'
                                 '（既不折成合规，也不折成违规）')
                elif body not in names:
                    findings.append(Finding(
                        'R16 说明书首行不是本案发明名称', path, fno,
                        f'首行「{body}」与同包交底书里的发明名称'
                        f'（{"／".join(names[:3])}）不是同一个——§4.2 逐字：'
                        '说明书第一页第一行应当写明发明名称，该名称应当与请求书中的名称一致'))

    # R8 EVT 投产总则逐字（铁律 5 / EVT 诚实边界）
    if EVT_DIR.search(path) or EVT_SCOPE.search(text):
        if PRODUCTION_CLAUSE not in text:
            findings.append(Finding(
                'R8 投产总则', path, 1,
                'EVT/投产文书缺逐字投产总则：' + PRODUCTION_CLAUSE[:24] + '…'))

    # R9 背景技术节的逐字查新声明（hard-rules §2 / templates §1「末尾统一查新声明句」）。
    # 只判本节：这句话是给"背景技术只引了初步检索"这件事兜底的，全文别处出现不算兑现；
    # 反过来，本节都没有（骨架底稿就只有附图说明＋标记说明两节）时报未判，不折成违规。
    bg_start, bg_body = section_body(lines, BACKGROUND_HEAD)
    if bg_start is None:
        notes.append('背景技术节未找到，R9 未判（不折成违规也不折成合规）')
    else:
        flat = re.sub(r'\s+', '', '\n'.join(bg_body))
        if NOVELTY_FLAT not in flat:
            findings.append(Finding(
                'R9 查新声明', path, bg_start,
                '背景技术节缺逐字查新声明：' + NOVELTY_CLAUSE[:20] + '…'))
        else:
            nonblank = [l.strip() for l in bg_body if l.strip()]
            if nonblank and NOVELTY_FLAT not in re.sub(r'\s+', '', nonblank[-1]):
                notes.append('R9 声明句在本节内但不在末尾（templates §1 要求置于末尾）——只提示不判红')
    return findings, notes


MAX_XML_BYTES = 32 * 1024 * 1024   # 单份 document.xml 的解压上限，常驻测试把它调小来验这道闸


def docx_text(path):
    """抽取 .docx 正文（只用 stdlib）。交付物是 docx，铁律不能只检 md——
    "md 改干净了、docx 还留着禁用词"正是本仓库记录在案的事故形状。

    段落标题按 w:pStyle 还原成 markdown 井号，让 R3/R4/R10 这类按节判的判据
    在 pandoc 产物上同样可用；非 pandoc 风格命名（标题样式对不上）时相应节
    找不到，会走各自的"未核"三态而不是判绿。（R7 不在这张名单里：它认的是
    `- 发明名称：` 那一行，与节标题还原无关。）

    表格按 w:tbl 还原成 markdown 管道行（表头后补一行 |---|）：Word 里的表格
    单元格本身也是 w:p，逐段吐出来的话整张表就散成一串裸行——按列读的判据
    （E/G/K/N 都靠 mdtable 认列）一律认不出这张表，症状是"交付件里有表却报无表"。
    只补一行分隔符还有第二个理由：mdtable 要求连续两行才算一张表，
    只有表头的 docx 表若不补分隔符就整张隐身，骨架期的"未判"会退化成"没有表"。"""
    import xml.etree.ElementTree as ET
    import zipfile
    # docx 可能是外部交付件，ET 的默认解析器不防实体展开（十亿 laugh）与 zip 炸弹。
    # 这里用两条前置拒绝代替引第三方库：document.xml 合法内容里不该有 DTD/ENTITY 声明，
    # 也不该有几十 MB 的解压尺寸。拒绝时说清成因并走 rc=2，不静默判绿。
    with zipfile.ZipFile(path) as z:
        info = z.getinfo('word/document.xml')
        if info.file_size > MAX_XML_BYTES:
            raise ValueError(f'document.xml 解压尺寸 {info.file_size} > {MAX_XML_BYTES}，疑为压缩炸弹')
        blob = z.read('word/document.xml')
    head = blob[:65536]
    for marker in (b'<!DOCTYPE', b'<!ENTITY'):
        if marker in head:
            raise ValueError(f'document.xml 含 {marker.decode()} 声明，拒绝解析（防实体展开）')
    root = ET.fromstring(blob)
    # 表格内部的段落由表格分支统一按格取文，段落分支要跳过它们，
    # 否则同一格文字既进 "| a | b |" 又进裸行，读起来像"表在、表内容也散在外面"。
    inside = set()
    for tbl in [e for e in root.iter() if e.tag.endswith('}tbl')]:
        for el in tbl.iter():
            inside.add(id(el))

    def txt(el):
        return ''.join((t.text or '') for t in el.iter() if t.tag.endswith('}t'))

    out = []
    for p in root.iter():
        if p.tag.endswith('}tbl'):
            rows = []
            for tr in p:
                if not tr.tag.endswith('}tr'):
                    continue
                cells = [txt(tc) for tc in tr if tc.tag.endswith('}tc')]
                rows.append('| ' + ' | '.join(cells) + ' |')
                if len(rows) == 1:
                    rows.append('|' + '---|' * len(cells))
            # 每行必须以换行收尾：mdtable 按行取列，四行连成一行的话整张表读不出来
            if rows:
                out.append('\n'.join(rows) + '\n')
            continue
        if id(p) in inside:
            continue
        if not p.tag.endswith('}p'):
            continue
        style = ''
        for el in p.iter():
            if el.tag.endswith('}pStyle'):
                style = el.get('{http://schemas.openxmlformats.org/wordprocessingml/2006/main}val', '')
        m = re.search(r'(?:Heading|标题|title)[\s_-]*(\d)', style, re.I)
        if style.lower().startswith('title'):
            out.append('# ')
        elif m:
            out.append('#' * int(m.group(1)) + ' ')
        out.append(txt(p))
        out.append('\n')
        # 嵌入的图形对象（插图/OLE/旧式 VML）在纯文本抽取里是**看不见的**，
        # 而 Q7 判的是"权利要求书里不得有插图"——不看这一行，Word 件上 Q7 永远是绿的瞎子。
        # 折算成一行 md 图片语法：Q7 的正则两通道吃同一份，别处没有判据扫这个形状。
        # 表格里的图不在此列（表格分支按格取文，见上）——登记为已知盲区，不是"已核无图"。
        if any(el.tag.endswith(('}drawing', '}object', '}pict')) for el in p.iter()):
            out.append('![](docx-embedded-object)\n')
    return ''.join(out)


def docx_graph_census(path):
    """docx 里"图形部件"的 zip 级普查：`word/media/*` 的条目数 ＋ `word/document.xml` 里
    drawing／object／pict 标签的出现数。不是 .docx ⇒ 0（md 通道没有这一层盲区，图片形状就在文本面上）。

    为什么需要这一把尺：`docx_text()` 只把**段落**里的图形对象折成一行
    `![](docx-embedded-object)`（本文件 docx_text 中 `}pStyle` 之后那一支），
    表格格子里嵌的图（表格分支按格取文）与页眉页脚里的图（它只读 word/document.xml）都读不到
    ⇒ 在这条通道上"文本面零命中"证明不了"没有插图"。
    读数**只用来决定要不要出一条未判 note**，本身不作违规依据：判违规仍然只认文本面上那一行。
    页眉／页脚那一类靠 media 条目抓到——嵌一张图必然带一个 word/media/ 部件
    （r73 量测轮那份页眉嵌图实测 media=1、document.xml 里 drawing 0，留底
    .codebuddy/attest/r73_figcriterion/readings.md，该目录不入 git）。
    media 只数非零字节的条目（目录条目与零字节占位不算一个部件）——与 `rebuild_package` 同一口径。
    读不动时**不吞异常**：main() 把它与 read_text 放在同一个 try 里，落 rc=2（输入不可用），
    而不是退化成"这份件没有图形部件"。"""
    if not path.lower().endswith('.docx'):
        return 0
    import zipfile
    with zipfile.ZipFile(path) as z:
        media = sum(1 for i in z.infolist()
                    if i.filename.startswith('word/media/') and i.file_size)
        ntags = len(DOCX_GRAPH_TAG.findall(z.read('word/document.xml')))
    return media + ntags


def read_text(path):
    """按扩展名分派读文本。docx 打不开/无 document.xml 时抛异常，由调用方转 rc=2。"""
    if path.lower().endswith('.docx'):
        return docx_text(path)
    return open(path, encoding='utf8').read()


def gather_files(args):
    if args.all:
        root = args.targets[0]
        out = []
        for dp, _, fs in os.walk(root):
            for f in sorted(fs):
                if f.lower().endswith(('.md', '.docx')):
                    out.append(os.path.join(dp, f))
        return out
    return args.targets


# 从本文件源码现取自己定义的判据号（`Finding(` 后面的 R 号）。模式与 tests/test_scripts.py 的
# `rule_span` 逐字同一把：`\d{1,2}` 不省成 `\d`（省了会把 R10 折成 1，断档从此看不见）、
# `\s*` 不省（R8 的换行写法会被整个漏掉）。两边各写一把就会分叉，所以这里的模式与那份对齐，
# 并由常驻档"提取器自己的两档"同时钉住两处（改一处另一处当场点名）。
RULE_ID_RE = re.compile(r"Finding\(\s*['\"]R(\d{1,2})")


def self_rule_span():
    """合计行的自报区间：从自己的源码推出 `R<首>–R<尾>`；推不动就返回 None。

    为什么不留一个字面量在这里：这一格从前写着"R1–R13"，本轮加 R14 之后它就是一句谎话，
    而谎话只有拿源码现推才看得见（`test_check_iron_rules` 那条"门禁自报规则区间与实际判据"
    就是拿源码现推的读数来比这一行打印出来的内容）。
    号有断档（说明推导式漏读了一个 token，或有人跳号）时**不报区间**：
    宁缺于一个假区间，也不为了有一行总结话而抄一份。"""
    try:
        src = open(os.path.abspath(__file__), encoding='utf8').read()
    except OSError:
        return None
    nums = sorted({int(x) for x in RULE_ID_RE.findall(src)})
    if not nums or nums != list(range(nums[0], nums[0] + len(nums))):
        return None
    return f'R{nums[0]}–R{nums[-1]}'


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('targets', nargs='+', help='待检 .md 或 .docx 文件，或配合 --all 传交付包目录')
    ap.add_argument('--all', action='store_true', help='递归检查目录下所有 .md 与 .docx')
    ap.add_argument('--search-report', help='检索报告 .md：提供 R5 的已核验公开号集合')
    ap.add_argument('--brand-terms', help='逗号分隔的本案型号/商标清单（R6）；不给则 R6 报未核')
    args = ap.parse_args()

    if args.all and not os.path.isdir(args.targets[0]):
        print(f'--all 需要目录，实得不是目录: {args.targets[0]}（未做任何判定）')
        sys.exit(2)
    paths = gather_files(args)
    bad = [p for p in paths if not os.path.isfile(p)]
    if bad:
        print('输入不可用，未做任何判定: ' + ', '.join(bad))
        sys.exit(2)
    if not paths:
        print(f'未找到待检文件（--all 目录下无 .md/.docx？）: {args.targets[0]}（未做任何判定）')
        sys.exit(2)

    allowed = None
    if args.search_report:
        if not os.path.isfile(args.search_report):
            print(f'检索报告不存在: {args.search_report}')
            sys.exit(2)
        allowed = set(re.sub(r'\s', '', x).upper()
                      for x in PUB_NO.findall(read_text(args.search_report)))
        print(f'检索报告已核验公开号 {len(allowed)} 个')

    brands = None
    if args.brand_terms is not None:
        brands = [t.strip() for t in args.brand_terms.split(',') if t.strip()]
        print(f'型号/商标清单 {len(brands)} 项: {", ".join(brands)}')

    total = 0
    docs = []
    for p in paths:
        try:
            # R14 的 census 与正文抽取同生死：zip 读不动就是输入不可用（rc=2），
            # 不能让它退化成"这份件没有图形部件"，那等于把 Word 件的盲区读成合规
            docs.append((p, read_text(p), docx_graph_census(p)))
        except Exception as e:
            # 抽不出正文就谈不上判定：说清成因并 rc=2，不折成"这份文书没有违规"
            print(f'输入不可用，未做任何判定: {p}（{type(e).__name__}: {e}）')
            sys.exit(2)
    # R12/R13 的号集是**包级**事实：那张「标记｜名称」表常写在另一份文书的附图说明节里，
    # 按单份文书各读各的，摘要侧就永远看不见表、永远报未判。
    marks = mark_map([t for _, t, _g in docs])
    for p, text, graphs in docs:
        if p.lower().endswith('.docx') and not re.search(r'^#{1,6}\s', text, re.M):
            # 节标题靠 w:pStyle 还原；样式名对不上（非 pandoc 产物）时按节／按区域判的判据
            # 根本找不到节（R11 与 R14 共用 `spec_doc_blocks` 那套区域，区域为空就是"没判"，
            # 连那条 census 未判行都长不出来），这时"违规 0"不等于核过，必须说明未核。
            # 名单不抄在这里，由 `SECTION_FACE_RULES` 渲染（读者看到的句子逐字不变）：
            # 那句自述漏一格就是把"看不见"说成"只影响那几条"，而它不报错、只少报——
            # 少报的东西必须由常驻现推对账逼出来，不能靠下一轮有人记得。
            print(f'  note {p}: 未识别到节标题样式 → {"/".join(SECTION_FACE_RULES)}'
                  f'（按节判的判据）未核')
        findings, notes = check_text(p, text, allowed, brands, marks, graphs)
        for note in notes:
            print(f'  note {p}: {note}')
        for f in findings:
            print(str(f))
        total += len(findings)
        print(f'{p}: 违规 {len(findings)}')
    # 自报区间一律现推，不手抄：这一格从前是字面的"R1–R13"，本轮加 R14 时它当场过期，
    # 而常驻"门禁自报规则区间与实际判据"那档拿 tests 的 rule_span（同一把模式）对账会点名。
    # 读不到源码或推导有断档时宁可写"区间未推"，也不报一个抄来的假区间。
    span = self_rule_span() or '区间未推'
    print(f'合计违规 {total}（规则 {span}，判据见脚本 docstring）')
    sys.exit(1 if total else 0)


if __name__ == '__main__':
    main()
